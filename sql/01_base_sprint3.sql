-- ============================================================
-- PROCEDIMENTO 2
-- Soma MANUALMENTE os saldos por agencia e conta.
-- Nao utiliza SUM, ROLLUP, CUBE, GROUPING SETS ou GROUPING.
-- ============================================================
CREATE OR REPLACE PROCEDURE SP_RELATORIO_SALDOS AS
    CURSOR C_SALDOS IS
        SELECT AGENCIA, CONTA, SALDO
        FROM TB_CONTA_SALDO
        ORDER BY AGENCIA, CONTA;

    V_AGENCIA_ATUAL NUMBER := NULL;
    V_SUBTOTAL NUMBER := 0;
    V_TOTAL_GERAL NUMBER := 0;
    V_TEM_REGISTRO BOOLEAN := FALSE;
    E_AGENCIA_INVALIDA EXCEPTION;
    E_SALDO_INVALIDO EXCEPTION;
BEGIN
    -- Validacao manual para gerar NO_DATA_FOUND se a tabela estiver vazia.
    DECLARE
        V_PRIMEIRA_AGENCIA NUMBER;
    BEGIN
        SELECT AGENCIA INTO V_PRIMEIRA_AGENCIA
        FROM TB_CONTA_SALDO
        WHERE ROWNUM = 1;
    END;

    DBMS_OUTPUT.PUT_LINE('Agencia  Conta  Saldo');
    DBMS_OUTPUT.PUT_LINE('-------  -----  --------');

    FOR R IN C_SALDOS LOOP
        V_TEM_REGISTRO := TRUE;

        IF R.AGENCIA IS NULL OR R.AGENCIA <= 0 THEN
            RAISE E_AGENCIA_INVALIDA;
        END IF;

        IF R.SALDO IS NULL OR R.SALDO < 0 THEN
            RAISE E_SALDO_INVALIDO;
        END IF;

        -- Quando a agencia muda, imprime o subtotal da agencia anterior.
        IF V_AGENCIA_ATUAL IS NOT NULL AND R.AGENCIA <> V_AGENCIA_ATUAL THEN
            DBMS_OUTPUT.PUT_LINE(
                '         Sub Total  ' || TO_CHAR(V_SUBTOTAL, 'FM999999990D00')
            );
            DBMS_OUTPUT.PUT_LINE('');
            V_SUBTOTAL := 0;
        END IF;

        V_AGENCIA_ATUAL := R.AGENCIA;

        -- Soma manual: uma conta por vez.
        V_SUBTOTAL := V_SUBTOTAL + R.SALDO;
        V_TOTAL_GERAL := V_TOTAL_GERAL + R.SALDO;

        DBMS_OUTPUT.PUT_LINE(
            RPAD(TO_CHAR(R.AGENCIA), 9) ||
            RPAD(TO_CHAR(R.CONTA), 7) ||
            TO_CHAR(R.SALDO, 'FM999999990D00')
        );
    END LOOP;

    IF NOT V_TEM_REGISTRO THEN
        RAISE NO_DATA_FOUND;
    END IF;

    -- Subtotal do ultimo grupo.
    DBMS_OUTPUT.PUT_LINE(
        '         Sub Total  ' || TO_CHAR(V_SUBTOTAL, 'FM999999990D00')
    );

    -- Total geral manual.
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE(
        '         Total Geral ' || TO_CHAR(V_TOTAL_GERAL, 'FM999999990D00')
    );

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('ERRO - A tabela TB_CONTA_SALDO nao possui registros.');
    WHEN VALUE_ERROR THEN
        DBMS_OUTPUT.PUT_LINE('ERRO - Valor numerico invalido durante o calculo.');
    WHEN E_AGENCIA_INVALIDA THEN
        DBMS_OUTPUT.PUT_LINE('ERRO - Agencia invalida encontrada nos dados.');
    WHEN E_SALDO_INVALIDO THEN
        DBMS_OUTPUT.PUT_LINE('ERRO - Saldo nulo ou negativo encontrado nos dados.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERRO inesperado: ' || SQLCODE || ' - ' || SQLERRM);
END;
/

