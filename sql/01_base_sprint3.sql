-- FUNCAO 1
-- Recebe o ID do pet e retorna uma string JSON construida
-- manualmente. Nao usa funcoes JSON built-in do Oracle.
-- ============================================================
CREATE OR REPLACE FUNCTION FN_PET_JSON(P_ID_PET TB_PET.ID_PET%TYPE)
RETURN VARCHAR2
AS
    V_NM_PET TB_PET.NM_PET%TYPE;
    V_ESPECIE TB_PET.ESPECIE%TYPE;
    V_RACA TB_PET.RACA%TYPE;
    V_PESO TB_PET.PESO%TYPE;
    V_NM_TUTOR TB_TUTOR.NM_TUTOR%TYPE;
    V_JSON VARCHAR2(4000);
    E_ID_INVALIDO EXCEPTION;
BEGIN
    IF P_ID_PET IS NULL OR P_ID_PET <= 0 THEN
        RAISE E_ID_INVALIDO;
    END IF;

    SELECT P.NM_PET, P.ESPECIE, P.RACA, P.PESO, T.NM_TUTOR
    INTO V_NM_PET, V_ESPECIE, V_RACA, V_PESO, V_NM_TUTOR
    FROM TB_PET P
    JOIN TB_TUTOR T ON T.ID_TUTOR = P.ID_TUTOR
    WHERE P.ID_PET = P_ID_PET;

    -- JSON montado por concatenacao de strings.
    V_JSON := '{' ||
        '"idPet":' || TO_CHAR(P_ID_PET) || ',' ||
        '"nome":"' || REPLACE(V_NM_PET, '"', '\"') || '",' ||
        '"especie":"' || REPLACE(V_ESPECIE, '"', '\"') || '",' ||
        '"raca":"' || REPLACE(NVL(V_RACA, ''), '"', '\"') || '",' ||
        '"peso":' || NVL(TO_CHAR(V_PESO, 'FM999999990D00'), 'null') || ',' ||
        '"tutor":"' || REPLACE(V_NM_TUTOR, '"', '\"') || '"' ||
        '}';

    RETURN V_JSON;
EXCEPTION
    WHEN E_ID_INVALIDO THEN
        RETURN '{"erro":"ID do pet invalido"}';
    WHEN NO_DATA_FOUND THEN
        RETURN '{"erro":"Pet nao encontrado"}';
    WHEN VALUE_ERROR THEN
        RETURN '{"erro":"Valor invalido na conversao"}';
    WHEN OTHERS THEN
        RETURN '{"erro":"Erro inesperado na funcao"}';
END;
/

-- ============================================================
-- FUNCAO 2
-- Classifica a prioridade do pet usando uma logica do projeto.
-- A funcao e usada para apoiar a analise do PetCare360.
-- ============================================================
CREATE OR REPLACE FUNCTION FN_CLASSIFICAR_RISCO(
    P_ID_PET NUMBER,
    P_TEMPERATURA NUMBER,
    P_ATIVIDADE NUMBER,
    P_ALIMENTACAO NUMBER
) RETURN VARCHAR2
AS
    V_NM_PET TB_PET.NM_PET%TYPE;
    V_PONTOS NUMBER := 0;
    E_TEMPERATURA_INVALIDA EXCEPTION;
    E_PERCENTUAL_INVALIDO EXCEPTION;
BEGIN
    SELECT NM_PET INTO V_NM_PET
    FROM TB_PET
    WHERE ID_PET = P_ID_PET;

    IF P_TEMPERATURA IS NULL OR P_TEMPERATURA < 30 OR P_TEMPERATURA > 45 THEN
        RAISE E_TEMPERATURA_INVALIDA;
    END IF;

    IF P_ATIVIDADE IS NULL OR P_ATIVIDADE < 0 OR P_ATIVIDADE > 100
       OR P_ALIMENTACAO IS NULL OR P_ALIMENTACAO < 0 OR P_ALIMENTACAO > 100 THEN
        RAISE E_PERCENTUAL_INVALIDO;
    END IF;

    IF P_TEMPERATURA >= 39.5 THEN V_PONTOS := V_PONTOS + 4;
    ELSIF P_TEMPERATURA >= 39 THEN V_PONTOS := V_PONTOS + 2;
    END IF;

    IF P_ATIVIDADE < 30 THEN V_PONTOS := V_PONTOS + 3;
    ELSIF P_ATIVIDADE < 50 THEN V_PONTOS := V_PONTOS + 1;
    END IF;

    IF P_ALIMENTACAO < 40 THEN V_PONTOS := V_PONTOS + 3;
    ELSIF P_ALIMENTACAO < 60 THEN V_PONTOS := V_PONTOS + 1;
    END IF;

    IF V_PONTOS >= 7 THEN
        RETURN 'ALTO';
    ELSIF V_PONTOS >= 4 THEN
        RETURN 'ATENCAO';
    ELSE
        RETURN 'NORMAL';
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'ERRO: PET NAO ENCONTRADO';
    WHEN E_TEMPERATURA_INVALIDA THEN
        RETURN 'ERRO: TEMPERATURA INVALIDA';
    WHEN E_PERCENTUAL_INVALIDO THEN
        RETURN 'ERRO: PERCENTUAL INVALIDO';
    WHEN VALUE_ERROR THEN
        RETURN 'ERRO: VALOR INVALIDO';
    WHEN OTHERS THEN
        RETURN 'ERRO: ' || SQLCODE;
END;
/

-- ============================================================
-- TRIGGER DE AUDITORIA DML
-- Registra INSERT, UPDATE e DELETE realizados em TB_PET.
-- ============================================================
CREATE OR REPLACE TRIGGER TRG_AUDITORIA_PET
AFTER INSERT OR UPDATE OR DELETE ON TB_PET
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO TB_AUDITORIA_PET (
            NM_USUARIO, TP_OPERACAO, DT_OPERACAO,
            VALORES_ANTERIORES, VALORES_NOVOS
        ) VALUES (
            USER,
            'INSERT',
            SYSTIMESTAMP,
            NULL,
            'ID_PET=' || :NEW.ID_PET ||
            '; NM_PET=' || :NEW.NM_PET ||
            '; ESPECIE=' || :NEW.ESPECIE ||
            '; PESO=' || :NEW.PESO ||
            '; ID_TUTOR=' || :NEW.ID_TUTOR
        );

    ELSIF UPDATING THEN
        INSERT INTO TB_AUDITORIA_PET (
            NM_USUARIO, TP_OPERACAO, DT_OPERACAO,
            VALORES_ANTERIORES, VALORES_NOVOS
        ) VALUES (
            USER,
            'UPDATE',
            SYSTIMESTAMP,
            'ID_PET=' || :OLD.ID_PET ||
            '; NM_PET=' || :OLD.NM_PET ||
            '; ESPECIE=' || :OLD.ESPECIE ||
            '; PESO=' || :OLD.PESO ||
            '; ID_TUTOR=' || :OLD.ID_TUTOR,
            'ID_PET=' || :NEW.ID_PET ||
            '; NM_PET=' || :NEW.NM_PET ||
            '; ESPECIE=' || :NEW.ESPECIE ||
            '; PESO=' || :NEW.PESO ||
            '; ID_TUTOR=' || :NEW.ID_TUTOR
        );

    ELSIF DELETING THEN
        INSERT INTO TB_AUDITORIA_PET (
            NM_USUARIO, TP_OPERACAO, DT_OPERACAO,
            VALORES_ANTERIORES, VALORES_NOVOS
        ) VALUES (
            USER,
            'DELETE',
            SYSTIMESTAMP,
            'ID_PET=' || :OLD.ID_PET ||
            '; NM_PET=' || :OLD.NM_PET ||
            '; ESPECIE=' || :OLD.ESPECIE ||
            '; PESO=' || :OLD.PESO ||
            '; ID_TUTOR=' || :OLD.ID_TUTOR,
            NULL
        );
    END IF;
END;
/

-- ============================================================
-- BLOCO LAG / LEAD DA SPRINT 2
-- Mantido para preservar o recurso apresentado anteriormente.
-- ============================================================
DECLARE
    CURSOR C_PESOS IS
        SELECT NM_PET, PESO,
               LAG(PESO) OVER (ORDER BY ID_PET) AS PESO_ANTERIOR,
               LEAD(PESO) OVER (ORDER BY ID_PET) AS PESO_PROXIMO
        FROM TB_PET;
    V_TOTAL NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=== RELATORIO DE PESOS ===');
    FOR R IN C_PESOS LOOP
        V_TOTAL := V_TOTAL + 1;
        DBMS_OUTPUT.PUT_LINE(
            'Pet: ' || R.NM_PET ||
            ' | Atual: ' || NVL(TO_CHAR(R.PESO), 'Vazio') ||
            ' | Anterior: ' || NVL(TO_CHAR(R.PESO_ANTERIOR), 'Vazio') ||
            ' | Proximo: ' || NVL(TO_CHAR(R.PESO_PROXIMO), 'Vazio')
        );
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('Total: ' || V_TOTAL);
EXCEPTION
    WHEN VALUE_ERROR THEN
        DBMS_OUTPUT.PUT_LINE('ERRO - Valor invalido no relatorio de pesos.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERRO - ' || SQLCODE || ' - ' || SQLERRM);
END;
/

